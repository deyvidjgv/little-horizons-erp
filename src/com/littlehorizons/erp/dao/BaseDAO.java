package com.littlehorizons.erp.dao;

import com.littlehorizons.erp.model.DatabaseValue;
import com.littlehorizons.erp.model.DocumentType;
import com.littlehorizons.erp.model.Person;
import com.littlehorizons.erp.util.DatabaseConnection;
import com.littlehorizons.erp.util.ErrorLogger;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * JDBC work shared by every DAO: open the connection, prepare the statement and close everything
 * with try-with-resources. Each DAO only writes its SQL, how to fill the parameters and how to turn
 * a row into an object, passed as lambdas.
 */
public abstract class BaseDAO {

    @FunctionalInterface
    protected interface ParameterSetter {
        void setParameters(PreparedStatement statement) throws SQLException;
    }

    @FunctionalInterface
    protected interface RowMapper<T> {
        T mapRow(ResultSet row) throws SQLException;
    }

    @FunctionalInterface
    protected interface TransactionWork<T> {
        T execute(Connection connection) throws SQLException;
    }

    @FunctionalInterface
    protected interface ItemSetter<T> {
        void setParameters(PreparedStatement statement, T item) throws SQLException;
    }

    protected <T> List<T> queryList(String sql, ParameterSetter parameters, RowMapper<T> mapper,
                                    String errorMessage) throws DataAccessException {
        try (Connection connection = DatabaseConnection.getInstance().getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            parameters.setParameters(statement);
            try (ResultSet rows = statement.executeQuery()) {
                List<T> result = new ArrayList<>();
                while (rows.next()) {
                    result.add(mapper.mapRow(rows));
                }
                return result;
            }
        } catch (SQLException e) {
            throw failure(errorMessage, e);
        }
    }

    protected <T> Optional<T> queryOne(String sql, ParameterSetter parameters, RowMapper<T> mapper,
                                       String errorMessage) throws DataAccessException {
        return queryList(sql, parameters, mapper, errorMessage).stream().findFirst();
    }

    /** Runs an UPDATE or a DELETE. @return the number of affected rows */
    protected int executeUpdate(String sql, ParameterSetter parameters, String errorMessage)
            throws DataAccessException {
        try (Connection connection = DatabaseConnection.getInstance().getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            parameters.setParameters(statement);
            return statement.executeUpdate();
        } catch (SQLException e) {
            throw failure(errorMessage, e);
        }
    }

    /** Runs an INSERT. @return the id generated by AUTO_INCREMENT */
    protected int executeInsert(String sql, ParameterSetter parameters, String errorMessage)
            throws DataAccessException {
        try (Connection connection = DatabaseConnection.getInstance().getConnection()) {
            return insert(connection, sql, parameters);
        } catch (SQLException e) {
            throw failure(errorMessage, e);
        }
    }

    /**
     * Runs several statements as a single unit: if one fails, rollback undoes the others, so the
     * database never keeps half of an operation.
     */
    protected <T> T inTransaction(TransactionWork<T> work, String errorMessage) throws DataAccessException {
        try (Connection connection = DatabaseConnection.getInstance().getConnection()) {
            connection.setAutoCommit(false);
            try {
                T result = work.execute(connection);
                connection.commit();
                return result;
            } catch (SQLException | RuntimeException e) {
                // Any failure, expected or not, undoes what the transaction already did.
                connection.rollback();
                throw e;
            }
        } catch (SQLException e) {
            throw failure(errorMessage, e);
        }
    }

    /** INSERT inside a transaction. @return the generated id */
    protected static int insert(Connection connection, String sql, ParameterSetter parameters) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            parameters.setParameters(statement);
            statement.executeUpdate();
            try (ResultSet keys = statement.getGeneratedKeys()) {
                if (!keys.next()) {
                    throw new SQLException("La base de datos no devolvió el id generado.");
                }
                return keys.getInt(1);
            }
        }
    }

    /** Query of a single number inside a transaction. @return the number, or 0 if there is no row */
    protected static int queryInt(Connection connection, String sql, ParameterSetter parameters) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            parameters.setParameters(statement);
            try (ResultSet row = statement.executeQuery()) {
                return row.next() ? row.getInt(1) : 0;
            }
        }
    }

    /** UPDATE or DELETE inside a transaction. @return the number of affected rows */
    protected static int update(Connection connection, String sql, ParameterSetter parameters) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            parameters.setParameters(statement);
            return statement.executeUpdate();
        }
    }

    /**
     * Saves many rows with the same statement in a single trip to the database, all in one transaction:
     * either every row is saved or none.
     *
     * @return how many rows were sent
     */
    protected <T> int executeBatch(String sql, List<T> items, ItemSetter<T> setter, String errorMessage)
            throws DataAccessException {
        return inTransaction(connection -> {
            try (PreparedStatement statement = connection.prepareStatement(sql)) {
                for (T item : items) {
                    setter.setParameters(statement, item);
                    statement.addBatch();
                }
                statement.executeBatch();
            }
            return items.size();
        }, errorMessage);
    }

    /** Fills parameters 1 to 6 with the document and the names, the first columns of every person table. */
    protected static void fillIdentity(PreparedStatement statement, Person person) throws SQLException {
        statement.setString(1, person.getDocumentType().getDatabaseValue());
        statement.setString(2, person.getDocumentNumber());
        statement.setString(3, person.getFirstName());
        statement.setString(4, person.getMiddleName());
        statement.setString(5, person.getFirstSurname());
        statement.setString(6, person.getSecondSurname());
    }

    protected static void mapIdentity(ResultSet row, Person person, String idColumn) throws SQLException {
        person.setId(row.getInt(idColumn));
        person.setDocumentType(DatabaseValue.fromDatabaseValue(DocumentType.class, row.getString("tipo_documento")));
        person.setDocumentNumber(row.getString("numero_documento"));
        person.setFirstName(row.getString("primer_nombre"));
        person.setMiddleName(row.getString("segundo_nombre"));
        person.setFirstSurname(row.getString("primer_apellido"));
        person.setSecondSurname(row.getString("segundo_apellido"));
    }

    private DataAccessException failure(String message, SQLException cause) {
        ErrorLogger.log(getClass().getSimpleName() + " - " + message, cause);
        return new DataAccessException(message, cause);
    }
}
